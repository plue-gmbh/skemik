  /* The standard the list is, which the catalogue names in place of the choices. */
  public function source(): string
  {
    return match ($this) {
      self::Currency => 'ISO 4217',
      self::Country => 'ISO 3166-1',
      self::Language => 'ISO 639-1',
    };
  }

  /** @return list<string> */
  public function codes(): array
  {
    return match ($this) {
      self::Currency => self::CURRENCIES,
      self::Country => self::COUNTRIES,
      self::Language => self::LANGUAGES,
    };
  }

  public function word(string $code, Locale $locale): string
  {
    foreach ([explode('-', $locale->tag)[0], 'en'] as $language) {
      $name = $this->named($code, $language);
      if ($name !== null && $name !== $code) {
        return mb_ucfirst($name);
      }
    }

    return $code;
  }

  private function named(string $code, string $language): ?string
  {
    if ($this === self::Currency) {
      $name = \ResourceBundle::create($language, 'ICUDATA-curr')
        ?->get('Currencies')?->get($code)?->get(1);

      return is_string($name) ? $name : null;
    }

    return $this === self::Country
      ? \Locale::getDisplayRegion('-' . $code, $language)
      : \Locale::getDisplayLanguage($code, $language);
  }
